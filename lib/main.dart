  }

  Future<void> _init() async {
    await _loadIqamaFromPrefs();
    _startIqamaListener();
    await _loadDefaultsFromPrefs();
    await _determinePositionAndFetch();
  }

  Future<void> _startIqamaListener() async {
    try {
      final docRef = FirebaseFirestore.instance.collection('mosque').doc('iqama');
      _iqamaSub = docRef.snapshots().listen((snap) async {
        if (snap.exists && snap.data() != null) {
          final data = snap.data()!;
          final newMap = <String, String>{};
          data.forEach((k, v) {
            if (v != null) newMap[k.toString()] = v.toString();
          });
          setState(() {
            _iqama = newMap;
            _usingRemoteIqama = true;
          });
          await _saveIqamaToPrefs(); // cache locally
        }
      }, onError: (err) {
        // listener may fail if user has no network - keep prefs
      });
    } catch (_) {
      // ignore - Firestore may not be configured
    }
  }

  Future<void> _loadDefaultsFromPrefs() async {
    final prefs = await SharedPreferences.getInstance();
    setState(() {
      _defaultLocation = prefs.getString('default_location') ?? '';
    });
  }

  Future<void> _saveDefaultLocation(String location) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('default_location', location);
    setState(() => _defaultLocation = location);
  }

  Future<void> _loadIqamaFromPrefs() async {
    final prefs = await SharedPreferences.getInstance();
    final raw = prefs.getString('iqama_map');
    if (raw != null) {
      try {
        final parsed = json.decode(raw) as Map<String, dynamic>;
        setState(() {
          _iqama = parsed.map((k, v) => MapEntry(k, v.toString()));
          _usingRemoteIqama = false;
        });
      } catch (_) {}
    }
  }

  Future<void> _saveIqamaToPrefs() async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('iqama_map', json.encode(_iqama));
  }

  Future<void> _saveIqamaToFirestore() async {
    // --- EDIT: If there's no Firebase user, don't attempt to save. ---
    final user = FirebaseAuth.instance.currentUser;
    if (user == null) {
      return;
    }

    try {
      final docRef = FirebaseFirestore.instance.collection('mosque').doc('iqama');
      await docRef.set(_iqama.map((k, v) => MapEntry(k, v)), SetOptions(merge: true));
      setState(() {
        _usingRemoteIqama = true;
      });
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('Failed to save iqama to server: $e')));
      }
    }
  }

  Future<void> _determinePositionAndFetch() async {
    setState(() => _loading = true);
    try {
      bool serviceEnabled = await Geolocator.isLocationServiceEnabled();
      if (!serviceEnabled) {
        throw Exception('Location services disabled');
      }

      LocationPermission permission = await Geolocator.checkPermission();
      if (permission == LocationPermission.denied) {
        permission = await Geolocator.requestPermission();
        if (permission == LocationPermission.denied) {
          throw Exception('Location permission denied');
        }
      }
      if (permission == LocationPermission.deniedForever) {
        throw Exception('Location permission permanently denied');
      }

      final pos = await Geolocator.getCurrentPosition(desiredAccuracy: LocationAccuracy.low);
      setState(() {
        _lastLat = pos.latitude;
        _lastLon = pos.longitude;
      });

      // Try platform reverse-geocode first (best-effort)
      try {
        final places = await placemarkFromCoordinates(pos.latitude, pos.longitude);
        if (places.isNotEmpty) {
          final p = places.first;
          final city = p.locality ?? p.subAdministrativeArea;
          final country = p.country;
          if ((city != null && city.isNotEmpty) || (country != null && country.isNotEmpty)) {
            setState(() {
              if (city != null && city.isNotEmpty) _city = city;
              if (country != null && country.isNotEmpty) _country = country!;
            });
          } else {
            // fallback to Nominatim if fields are sparse
            await _reverseGeocodeNominatim(pos.latitude, pos.longitude);
          }
        } else {
          // no placemarks -> fallback
          await _reverseGeocodeNominatim(pos.latitude, pos.longitude);
        }
      } catch (_) {
        // silent fallback to Nominatim
        await _reverseGeocodeNominatim(pos.latitude, pos.longitude);
      }

      final map = await PrayerTimesService.fetchByCoordinates(
        latitude: pos.latitude,
        longitude: pos.longitude,
        method: 2,
      );

      setState(() {
        _timings = map;
        for (final k in _timings.keys) {
          _iqama.putIfAbsent(k, () => _timings[k]!);
        }
        _loading = false;
      });

      await _saveIqamaToPrefs();
      await _applyThemeBySunset();
      _startCountdownLoop();
    } catch (e) {
      setState(() {
        _loading = false;
      });

      // if user provided a default location, use that
      if (_defaultLocation.isNotEmpty) {
        setState(() {
          _city = _defaultLocation;
        });
      } else {
        // best-effort fallback: try IP-based lookup when GPS/permission fails
        try {
          await _ipLookupFallback();
        } catch (_) {}
      }

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('Failed to load location/timings: $e')));
      }
    }
  }

  void _startCountdownLoop() {
    _countdownTimer?.cancel();
    _updateNextPrayer();
    _countdownTimer = Timer.periodic(const Duration(seconds: 1), (_) {
      _updateNextPrayer();
    });
  }

  void _startBlackoutTimer() {
    _blackoutTimer?.cancel();
    final endsAt = _blackoutEndsAt;
    if (endsAt == null) return;
    final remaining = endsAt.difference(DateTime.now());
    if (remaining.isNegative) {
      setState(() {
        _blackoutActive = false;
        _blackoutEndsAt = null;
      });
      return;
    }
    _blackoutTimer = Timer(remaining, () {
      if (mounted) {
        setState(() {
          _blackoutActive = false;
          _blackoutEndsAt = null;
        });
      }
    });
  }

  void _updateNextPrayer() {
    if (_timings.isEmpty) return;

    final now = DateTime.now();
    final entriesOrder = ['Fajr', 'Sunrise', 'Dhuhr', 'Asr', 'Maghrib', 'Isha'];
    final pairs = <MapEntry<String, DateTime>>[];

    // iterate in canonical prayer order and prefer Iqama when available
    for (final name in entriesOrder) {
      final azan = _timings[name];
      final iq = _iqama[name];
      final src = (iq != null && iq.trim().isNotEmpty) ? iq : azan;
      if (src == null) continue;
      final parsed = _parseTimeForToday(src);
      if (parsed != null) pairs.add(MapEntry(name, parsed));
    }

    // sort by time of day
    pairs.sort((a, b) => a.value.compareTo(b.value));

    MapEntry<String, DateTime>? next;
    for (final p in pairs) {
      if (p.value.isAfter(now) || _isSameMinute(p.value, now)) {
        next = p;
        break;
      }
    }

    // if none remaining today, choose the first prayer tomorrow
    if (next == null && pairs.isNotEmpty) {
      final tomorrowFirst = pairs.first;
      final tomorrow = DateTime(now.year, now.month, now.day + 1, tomorrowFirst.value.hour, tomorrowFirst.value.minute);
      next = MapEntry(tomorrowFirst.key, tomorrow);
    }

    if (next != null) {
      final nextEntry = next;
      final diff = nextEntry.value.difference(now);
      final remainingSeconds = diff.isNegative ? 0 : diff.inSeconds;
      final nextName = _normalizePrayerName(nextEntry.key);

      // detect whether this next prayer is using iqama time specifically
      final isIqamaNext = _iqama[nextEntry.key] != null && _iqama[nextEntry.key]!.trim().isNotEmpty;

      // Iqama special behaviour:
      // - Show full-screen countdown at T <= 60 and >5
      // - At T <= 5: start blackout (7 minutes)
      if (isIqamaNext && !_blackoutActive) {
        if (remainingSeconds <= 60 && remainingSeconds > 5) {
          if (!_showFullScreenCountdown) {
            setState(() {
              _showFullScreenCountdown = true;
            });
          }
        } else if (remainingSeconds <= 5) {
          if (!_blackoutActive) {
            setState(() {
              _showFullScreenCountdown = false;
              _blackoutActive = true;
              _blackoutEndsAt = DateTime.now().add(const Duration(minutes: 7));
            });
            _startBlackoutTimer();
          }
        } else {
          if (_showFullScreenCountdown) {
            setState(() {
              _showFullScreenCountdown = false;
            });
          }
        }
      }

      // Ensure blackout clears when its time passes (safety)
      if (_blackoutActive && _blackoutEndsAt != null && DateTime.now().isAfter(_blackoutEndsAt!)) {
        setState(() {
          _blackoutActive = false;
          _blackoutEndsAt = null;
        });
      }

      if (mounted) {
        setState(() {
          _timeToNext = diff.isNegative ? Duration.zero : diff;
          _nextPrayer = nextName;
        });
      }
    }
  }

  DateTime? _parseTimeForToday(String raw) {
    if (raw.trim().isEmpty) return null;

    final lower = raw.toLowerCase();
    int dayOffset = 0;
    if (lower.contains('next') || lower.contains('tomorrow') || lower.contains('next day')) {
      dayOffset = 1;
    }

    final cleaned = raw.replaceAll(RegExp(r"\(.*?\)"), '').trim();

    final timeMatch = RegExp(r'([0-9]{1,2}:[0-9]{2}(?:\s*[apAP][\.]?m[\.]?)?)').firstMatch(cleaned);
    String? timeToken = timeMatch?.group(1)?.trim();
    if (timeToken == null) {
      final m2 = RegExp(r'([0-9]{1,2}:[0-9]{2})').firstMatch(cleaned);
      timeToken = m2?.group(1);
    }
    if (timeToken == null) return null;

    timeToken = timeToken.replaceAll('.', '').toUpperCase();

    timeToken = timeToken.replaceAllMapped(RegExp(r'([0-9])([AP]M)$'), (m) => '${m.group(1)} ${m.group(2)}');

    int hour = 0;
    int minute = 0;
    try {
      if (timeToken.contains(RegExp(r'[AP]M'))) {
        final parsed = DateFormat.jm().parse(timeToken);
        hour = parsed.hour;
        minute = parsed.minute;
      } else {
        final parts = timeToken.split(':');
        hour = int.parse(parts[0]);
        minute = int.parse(parts[1]);
      }
    } catch (_) {
      return null;
    }

    final now = DateTime.now();
    final dt = DateTime(now.year, now.month, now.day + dayOffset, hour, minute);
    return dt;
  }

  bool _isSameMinute(DateTime a, DateTime b) =>
      a.year == b.year && a.month == b.month && a.day == b.day && a.hour == b.hour && a.minute == b.minute;

  String _normalizePrayerName(String raw) {
    final lower = raw.toLowerCase();
    if (lower.contains('fajr')) return 'Fajr';
    if (lower.contains('dhuhr') || lower.contains('zuhr')) return 'Dhuhr';
    if (lower.contains('asr')) return 'Asr';
    if (lower.contains('maghrib') || lower.contains('sunset')) return 'Maghrib';
    if (lower.contains('isha')) return 'Isha';
    if (lower.contains('sunrise')) return 'Sunrise';
    return raw.isNotEmpty ? '${raw[0].toUpperCase()}${raw.substring(1)}' : raw;
  }

  /// Apply theme (light/dark) based on sunset/maghrib time in the fetched timings.
  Future<void> _applyThemeBySunset() async {
    try {
      final maghribRaw = _timings['Maghrib'] ?? _timings['Sunset'] ?? '';
      final sunriseRaw = _timings['Sunrise'] ?? '';

      final maghrib = _parseTimeForToday(maghribRaw);
      final sunrise = _parseTimeForToday(sunriseRaw);

      if (maghrib == null || sunrise == null) return;

      final now = DateTime.now();
      final shouldDark = now.isAfter(maghrib) || now.isBefore(sunrise);
      await widget.onToggleTheme(shouldDark, manual: false);
    } catch (_) {}
  }

  String _displayLocation() {
    if (_city != 'Unknown' && _city.trim().isNotEmpty) return '$_city${_country.isNotEmpty ? ', $_country' : ''}';
    if (_lastLat != null && _lastLon != null) return '${_lastLat!.toStringAsFixed(3)}, ${_lastLon!.toStringAsFixed(3)}';
    return 'Unknown';
  }

