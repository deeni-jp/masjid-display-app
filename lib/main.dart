    final ok = await _ensureAdminSignedIn();
    if (!ok) return;
    setState(() => _adminMode = true);
    if (mounted) ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('Admin mode enabled')));
  }

  Future<void> _signOutAdmin() async {
    // --- EDIT: Handle local admin sign out ---
    // If a real Firebase user is signed in, sign them out.
    // Otherwise, just disable admin mode.
    if (FirebaseAuth.instance.currentUser != null) {
      try {
        await FirebaseAuth.instance.signOut();
      } catch (_) {}
    }
    setState(() {
      _adminMode = false;
    });
    if (mounted) ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('Signed out')));
  }

  Future<void> _editIqama(String prayer) async {
    // The UI should prevent this function from being called if not in admin mode.
    if (!_adminMode) return;

    final initial = _iqama[prayer] ?? _timings[prayer] ?? '';
    String value = initial;
    final result = await showDialog<String>(
      context: context,
      builder: (context) {
        return AlertDialog(
          title: Text('Edit Iqama - $prayer'),
          content: TextField(
            autofocus: true,
            keyboardType: TextInputType.datetime,
            decoration: const InputDecoration(hintText: 'HH:mm', labelText: 'Iqama time', helperText: 'e.g. 12:15'),
            controller: TextEditingController(text: initial),
            onChanged: (v) => value = v,
          ),
          actions: [
            TextButton(onPressed: () => Navigator.pop(context), child: const Text('Cancel')),
            ElevatedButton(onPressed: () => Navigator.pop(context, value), child: const Text('Save')),
          ],
        );
      },
    );

    if (result != null) {
      setState(() {
        _iqama[prayer] = result;
      });
      await _saveIqamaToPrefs();
      await _saveIqamaToFirestore();
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(const SnackBar(content: Text('Iqama updated')));
    }
  }

