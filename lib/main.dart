  Widget _buildCountdownCard(BuildContext context) {
    final nextSeconds = _timeToNext.inSeconds.toDouble();
    final percent = (1 - (nextSeconds / (6 * 3600))).clamp(0.0, 1.0);

    final hh = _timeToNext.inHours.toString().padLeft(2, '0');
    final mm = _timeToNext.inMinutes.remainder(60).toString().padLeft(2, '0');
    final ss = _timeToNext.inSeconds.remainder(60).toString().padLeft(2, '0');

    return Card(
      shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
      child: Padding(
        padding: const EdgeInsets.all(20.0),
        child: Column(mainAxisSize: MainAxisSize.min, children: [
          Text(_nextPrayer.isEmpty ? 'Next' : _nextPrayer, style: Theme.of(context).textTheme.titleLarge),
          const SizedBox(height: 12),
          Stack(alignment: Alignment.center, children: [
            SizedBox(
              width: 160,
              height: 160,
              child: CircularProgressIndicator(value: percent, strokeWidth: 8),
