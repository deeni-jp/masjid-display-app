class PrayerRow extends StatelessWidget {
  final String prayer;
  final String waqt;
  final String iqama;
  final bool adminMode;
  final VoidCallback? onEdit;

  const PrayerRow({super.key, required this.prayer, required this.waqt, required this.iqama, this.adminMode = false, this.onEdit});

  @override
  Widget build(BuildContext context) {
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 6.0, horizontal: 4.0),
      child: Row(children: [
        // Prayer column with icon + text
        Expanded(
          flex: 3,
          child: Row(
            children: [
              Container(
                width: 36,
                height: 36,
                decoration: BoxDecoration(
                  color: _iconColorForPrayer(prayer, context),
                  shape: BoxShape.circle,
                ),
                child: Icon(_iconForPrayer(prayer), size: 18, color: Colors.white),
              ),
              const SizedBox(width: 10),
              Expanded(child: Text(prayer, style: Theme.of(context).textTheme.bodyLarge)),
            ],
          ),
        ),

        // Azan / waqt
        Expanded(flex: 2, child: Text(_trimTime(waqt), textAlign: TextAlign.center, style: Theme.of(context).textTheme.bodyMedium)),

        // Iqama
        Expanded(
          flex: 2,
          child: Row(mainAxisAlignment: MainAxisAlignment.center, children: [
            Text(_trimTime(iqama), textAlign: TextAlign.center, style: Theme.of(context).textTheme.bodyMedium),
            if (adminMode) IconButton(icon: const Icon(Icons.edit, size: 18), onPressed: onEdit),
          ]),
        ),
      ]),
    );
  }

  IconData _iconForPrayer(String p) {
    switch (p.toLowerCase()) {
      case 'fajr':
        return Icons.wb_twilight;
      case 'dhuhr':
        return Icons.wb_sunny;
      case 'asr':
        return Icons.wb_sunny_outlined;
      case 'maghrib':
        return Icons.wb_twilight;
      case 'isha':
        return Icons.nightlight_round;
      case 'sunrise':
        return Icons.wb_sunny_outlined;
      default:
        return Icons.access_time;
    }
  }

  Color _iconColorForPrayer(String p, BuildContext context) {
    final lc = p.toLowerCase();
    final cs = Theme.of(context).colorScheme;
    if (lc.contains('fajr')) return cs.primary.withOpacity(0.92);
    if (lc.contains('dhuhr') || lc.contains('zuhr')) return Colors.orange.shade600;
    if (lc.contains('asr')) return Colors.amber.shade700;
    if (lc.contains('maghrib')) return Colors.deepOrange.shade600;
    if (lc.contains('isha')) return Colors.deepPurple.shade700;
    if (lc.contains('sunrise')) return Colors.teal.shade600;
    return cs.primary;
  }

  String _trimTime(String raw) {
    final m = RegExp(r'([0-9]{1,2}:[0-9]{2}(?:\s*[APMapm]{0,4})?)').firstMatch(raw);
    return m?.group(1) ?? raw;
  }
}

class PrayerTimesService {
  static Future<Map<String, String>> fetchByCoordinates({
    required double latitude,
    required double longitude,
    int method = 2,
  }) async {
    final url = Uri.parse('https://api.aladhan.com/v1/timings?latitude=$latitude&longitude=$longitude&method=$method');
    final res = await http.get(url).timeout(const Duration(seconds: 10));
    if (res.statusCode != 200) throw Exception('HTTP ${res.statusCode}');
    final body = json.decode(res.body) as Map<String, dynamic>;
    if (body['code'] != 200) throw Exception('API error: ${body['status']}');
    final data = body['data'] as Map<String, dynamic>;
    final timings = data['timings'] as Map<String, dynamic>;
    final out = <String, String>{};
    for (final k in timings.keys) out[k] = timings[k].toString();
    return out;
  }
}
