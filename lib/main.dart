  /// Try reverse-geocoding via Nominatim (OpenStreetMap).
  Future<void> _reverseGeocodeNominatim(double lat, double lon) async {
    try {
      final uri = Uri.parse('https://nominatim.openstreetmap.org/reverse?format=jsonv2&lat=$lat&lon=$lon&accept-language=en');
      final res = await http.get(uri, headers: {
        // Please change the contact to a real email/domain for production
        'User-Agent': 'PrayerApp/1.0 (contact@example.com)'
      }).timeout(const Duration(seconds: 8));

      if (res.statusCode == 200) {
        final body = json.decode(res.body) as Map<String, dynamic>;
        final address = body['address'] as Map<String, dynamic>?;

        if (address != null) {
          final city = address['city'] ?? address['town'] ?? address['village'] ?? address['county'] ?? address['state'];
          final country = address['country'];

          setState(() {
            if (city != null && city.toString().isNotEmpty) _city = city.toString();
            if (country != null && country.toString().isNotEmpty) _country = country.toString();
          });
        }
      }
    } catch (e) {
      // ignore -> fallback may be used elsewhere
    }
  }

  /// Fallback: use an IP-based geolocation when GPS/permissions are unavailable.
  Future<void> _ipLookupFallback() async {
    try {
      final uri = Uri.parse('https://ipapi.co/json/');
      final res = await http.get(uri).timeout(const Duration(seconds: 6));
      if (res.statusCode == 200) {
        final body = json.decode(res.body) as Map<String, dynamic>;
        final city = body['city'] as String?;
        final country = body['country_name'] as String?;
        setState(() {
          if (city != null && city.isNotEmpty) _city = city;
          if (country != null && country.isNotEmpty) _country = country;
        });
      }
    } catch (_) {}
  }
